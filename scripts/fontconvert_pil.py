#!/usr/bin/env python3
"""
Drop-in alternative to scripts/fontconvert.py that uses Pillow (no freetype-py needed).
Produces the same epdiy/LilyGo GFXfont header format (4-bit, optionally zlib-compressed).

usage: fontconvert_pil.py NAME SIZE_PT FONT.ttf [--compress] [--ranges 0x20-0x7E,0xA0-0x17F] > out.h
Size is in points at 150 dpi, like the original script.
"""
import argparse, math, sys, zlib
from PIL import ImageFont

DEFAULT_RANGES = "0x20-0x7E,0xA0-0x17F,0x2013-0x2014,0x2018-0x201E,0x2022-0x2022,0x2026-0x2026,0x20AC-0x20AC"

p = argparse.ArgumentParser()
p.add_argument("name"); p.add_argument("size", type=int); p.add_argument("font")
p.add_argument("--compress", action="store_true")
p.add_argument("--ranges", default=DEFAULT_RANGES)
a = p.parse_args()

intervals = []
for part in a.ranges.split(","):
    s, e = part.split("-")
    intervals.append((int(s, 16), int(e, 16)))
intervals.sort()

px_size = round(a.size * 150 / 72)
font = ImageFont.truetype(a.font, px_size)
ascent, descent = font.getmetrics()

glyphs, data = [], bytearray()
for s, e in intervals:
    for cp in range(s, e + 1):
        ch = chr(cp)
        adv = int(math.floor(font.getlength(ch)))
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        if w == 0 or h == 0:
            w = h = 0
        buf = bytearray()
        for y in range(h):
            row = [mask.getpixel((x, y)) for x in range(w)]
            for x in range(0, w, 2):
                lo = row[x] >> 4
                hi = (row[x + 1] & 0xF0) if x + 1 < w else 0
                buf.append(lo | hi)
        packed = zlib.compress(bytes(buf)) if a.compress else bytes(buf)
        # anchor "ls": origin at left/baseline -> oy is offset of bitmap top from baseline (negative = above)
        glyphs.append((w, h, adv, ox, -oy, len(packed), len(data), cp))
        data += packed
        assert w < 256 and h < 256 and adv < 256, f"glyph too large for uint8 fields: {ch}"

out = sys.stdout
out.write('#pragma once\n#include "epd_driver.h"\n')
out.write(f"// generated by fontconvert_pil.py from {a.font.split('/')[-1]}, {a.size}pt @150dpi\n")
out.write(f"const uint8_t {a.name}Bitmaps[{len(data)}] = {{\n")
for i in range(0, len(data), 16):
    out.write("    " + " ".join(f"0x{b:02X}," for b in data[i:i+16]) + "\n")
out.write("};\n")
out.write(f"const GFXglyph {a.name}Glyphs[] = {{\n")
for g in glyphs:
    c = chr(g[7])
    label = "<backslash>" if c == "\\" else ("U+%04X" % g[7] if g[7] < 0x21 or 0x7F <= g[7] < 0xA1 else c)
    out.write("    { " + ", ".join(str(v) for v in g[:7]) + f" }}, // {label}\n")
out.write("};\n")
out.write(f"const UnicodeInterval {a.name}Intervals[] = {{\n")
off = 0
for s, e in intervals:
    out.write(f"    {{ 0x{s:X}, 0x{e:X}, 0x{off:X} }},\n"); off += e - s + 1
out.write("};\n")
out.write(f"const GFXfont {a.name} = {{\n    (uint8_t*){a.name}Bitmaps,\n    (GFXglyph*){a.name}Glyphs,\n"
          f"    (UnicodeInterval*){a.name}Intervals,\n    {len(intervals)},\n    {1 if a.compress else 0},\n"
          f"    {ascent + descent},\n    {ascent},\n    {-descent},\n}};\n")
print(f"{a.name}: {len(glyphs)} glyphs, {len(data)} bytes, advance_y={ascent+descent}", file=sys.stderr)
